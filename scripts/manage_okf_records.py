def _require_executable_bit(
    path: Path | None,
    *,
    label: str,
    blockers: list[str],
) -> None:
    if path is None:
        return
    try:
        mode = path.stat().st_mode
    except OSError as exc:
        blockers.append(f"{label} cannot be inspected: {exc}")
        return
    if not mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH):
        blockers.append(f"{label} must have an executable bit")


def _require_https_url(
    value: Any,
    *,
    label: str,
    blockers: list[str],
) -> str | None:
    if value is _MISSING:
        return None
    if not isinstance(value, str) or not value.strip():
        blockers.append(f"{label} must be a non-empty HTTPS URL")
        return None
    raw = value.strip()
    if len(raw) > 2_048:
        blockers.append(f"{label} exceeds its size limit")
        return None
    try:
        parsed = urlsplit(raw)
        port = parsed.port or 443
    except ValueError:
        blockers.append(f"{label} must be a valid HTTPS URL")
        return None
    if (
        parsed.scheme.lower() != "https"
        or not parsed.hostname
        or parsed.username is not None
        or parsed.password is not None
        or parsed.query
        or parsed.fragment
        or port != 443
    ):
        blockers.append(
            f"{label} must be public HTTPS without credentials, query, fragment, "
            "or a non-default port"
        )
        return None
    try:
        host = parsed.hostname.rstrip(".").encode("idna").decode("ascii").lower()
    except UnicodeError:
        blockers.append(f"{label} has an invalid hostname")
        return None
    if not host or host == "localhost" or host.endswith(".localhost"):
        blockers.append(f"{label} must use a public hostname")
        return None
    try:
        literal = ipaddress.ip_address(host)
    except ValueError:
        pass
    else:
        if not literal.is_global:
            blockers.append(f"{label} must not use a non-public IP address")
            return None
        host = literal.compressed
    host_text = f"[{host}]" if ":" in host else host
    path = parsed.path or "/"
    return urlunsplit(("https", host_text, path, "", ""))


