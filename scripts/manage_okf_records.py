def _normalize_root(root: str | os.PathLike[str]) -> Path:
    return Path(root).expanduser().resolve()


def _normalized_key(key: str) -> str:
    return re.sub(r"[^a-z0-9]", "", key.lower())


def _json_object(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    value: dict[str, Any] = {}
    for key, item in pairs:
        if key in value:
            raise _DuplicateKeyError(f"duplicate JSON key {key!r}")
        value[key] = item
    return value


def _reject_json_constant(value: str) -> None:
    raise ValueError(f"non-finite JSON number {value!r} is not allowed")


def _load_json(path: Path) -> Any:
    try:
        return json.loads(
            path.read_text(encoding="utf-8"),
            object_pairs_hook=_json_object,
            parse_constant=_reject_json_constant,
        )
    except (OSError, UnicodeError, json.JSONDecodeError, ValueError) as exc:
        raise ValueError(f"{path}: invalid JSON: {exc}") from exc


def _canonical_json_bytes(value: Any) -> bytes:
    try:
        return json.dumps(
            value,
            ensure_ascii=False,
            allow_nan=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    except (TypeError, ValueError) as exc:
        raise ValueError("value is not finite JSON data") from exc


def _pretty_json(value: Any) -> str:
    return json.dumps(
        value,
        ensure_ascii=False,
        allow_nan=False,
        indent=2,
        sort_keys=True,
    ) + "\n"


def _write_new_private(path: Path, data: bytes) -> bool:
    """Write a new private file without replacing any existing filesystem entry."""

    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return False
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
    except BaseException:
        try:
            path.unlink()
        except OSError:
            pass
        raise
    return True


def _atomic_write_private(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=path.parent,
    )
    temporary_path = Path(temporary_name)
    try:
        os.fchmod(descriptor, 0o600)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary_path, path)
    finally:
        try:
            temporary_path.unlink()
        except FileNotFoundError:
            pass


def _ensure_private_directory(path: Path) -> None:
    if path.exists() and (not path.is_dir() or path.is_symlink()):
        raise WorkspaceValidationError((f"{path}: expected a real directory",))
    path.mkdir(parents=True, exist_ok=True)
    os.chmod(path, 0o700)


def _validate_manifest_value(value: Any, *, label: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise WorkspaceValidationError((f"{label}: manifest must be a JSON object",))
    errors: list[str] = []
    expected = {
        "schemaVersion": WORKSPACE_SCHEMA,
        "private": True,
        "automaticSubmission": False,
        "movesFunds": False,
    }
    for key, required in expected.items():
        actual = value.get(key)
        if isinstance(required, bool):
            matches = actual is required
        else:
            matches = actual == required
        if not matches:
            errors.append(f"{label}: {key} must be {required!r}")
    if errors:
        raise WorkspaceValidationError(errors)
    return value


def _template_kind(path: Path, value: Any) -> str:
    if isinstance(value, Mapping) and value.get("recordKind") in RECORD_KINDS:
        return str(value["recordKind"])
    base = path.name.removesuffix(".template.json")
    if base in RECORD_KINDS:
        return base
    singular_to_kind = {
        "partner": "partners",
        "consent": "consents",
        "pilot": "pilots",
        "authorization": "authorizations",
        "proposal": "proposals",
        "payment": "payments",
        "fulfillment": "fulfillments",
        "finance": "financial",
        "evidence": "evidence",
        "video": "videos",
        "devpost": "devpost",
        "decision": "decisions",
        "risk": "risks",
    }
    if base in singular_to_kind:
        return singular_to_kind[base]
    raise WorkspaceValidationError(
        (f"{path}: template must declare a known recordKind",)
    )


def init_workspace(root: str | os.PathLike[str]) -> dict[str, Any]:
    """Initialize an idempotent private workspace without overwriting user files."""

    workspace = _normalize_root(root)
    manifest_path = workspace / ".okf-workspace.json"

    if manifest_path.exists():
        manifest = _load_json(manifest_path)
        _validate_manifest_value(manifest, label=".okf-workspace.json")

    _ensure_private_directory(workspace)
    for directory in (
        workspace / "records",
        workspace / "wiki",
        workspace / "runtime",
        workspace / "runtime" / "sqlite",
        workspace / "runtime" / "private-evidence",
        workspace / "publication-staging",
    ):
        _ensure_private_directory(directory)
    for kind in RECORD_KINDS:
        for base in ("records", "wiki"):
            directory = workspace / base / kind
            _ensure_private_directory(directory)

    manifest_created = _write_new_private(
        manifest_path,
        _pretty_json(
            {
                "automaticSubmission": False,
                "movesFunds": False,
                "private": True,
                "recordKinds": list(RECORD_KINDS),
                "schemaVersion": WORKSPACE_SCHEMA,
            }
        ).encode("utf-8"),
    )
    if manifest_path.is_symlink() or not manifest_path.is_file():
        raise WorkspaceValidationError(
            (f"{manifest_path}: manifest must be a regular non-symlink file",)
        )
    os.chmod(manifest_path, 0o600)

    copied_templates: list[str] = []
    if TEMPLATE_DIR.is_dir():
        for source in sorted(TEMPLATE_DIR.glob("*.template.json")):
            if not source.is_file():
                continue
            value = _load_json(source)
            kind = _template_kind(source, value)
            destination = workspace / "records" / kind / source.name
            if _write_new_private(destination, source.read_bytes()):
                copied_templates.append(destination.relative_to(workspace).as_posix())
            if destination.is_file() and not destination.is_symlink():
                os.chmod(destination, 0o600)

    return {
        "copiedTemplates": copied_templates,
        "manifestCreated": manifest_created,
        "root": str(workspace),
        "status": "initialized",
    }


def _required_text(
    value: Any,
    *,
    label: str,
    errors: list[str],
    slug: bool = False,
) -> str | None:
    if not isinstance(value, str) or not value:
        errors.append(f"{label} must be a non-empty string")
        return None
    if any(ord(character) < 32 for character in value):
        errors.append(f"{label} must not contain control characters")
        return None
    if slug and not SLUG_PATTERN.fullmatch(value):
        errors.append(f"{label} must be a lowercase hyphenated slug")
        return None
    return value


def _parse_utc_timestamp(
    value: Any,
    *,
    label: str,
    errors: list[str],
) -> datetime | None:
    if not isinstance(value, str) or not UTC_TIMESTAMP_PATTERN.fullmatch(value):
        errors.append(f"{label} must be an ISO-8601 UTC timestamp ending in Z")
        return None
    try:
        parsed = datetime.fromisoformat(value.removesuffix("Z") + "+00:00")
    except ValueError:
        errors.append(f"{label} is not a valid calendar timestamp")
        return None
    if parsed.utcoffset() != timezone.utc.utcoffset(parsed):
        errors.append(f"{label} must be UTC")
        return None
    return parsed


def _walk_json(
    value: Any,
    *,
    path: str,
    key_visitor: Any,
    string_visitor: Any | None = None,
) -> None:
    if isinstance(value, Mapping):
        for key, child in value.items():
            child_path = f"{path}.{key}"
            key_visitor(str(key), child_path)
            _walk_json(
                child,
                path=child_path,
                key_visitor=key_visitor,
                string_visitor=string_visitor,
            )
    elif isinstance(value, list):
        for index, child in enumerate(value):
            _walk_json(
                child,
                path=f"{path}[{index}]",
                key_visitor=key_visitor,
                string_visitor=string_visitor,
            )
    elif isinstance(value, str) and string_visitor is not None:
        string_visitor(value, path)


def _scan_record_security(
    value: Mapping[str, Any],
    *,
    label: str,
    public_redacted: bool,
    errors: list[str],
) -> None:
    def visit_key(key: str, location: str) -> None:
        normalized = _normalized_key(key)
        if normalized in CREDENTIAL_KEYS or any(
            normalized.endswith(forbidden) for forbidden in CREDENTIAL_KEYS
        ):
            errors.append(
                f"{label}: forbidden credential-bearing key at {location}"
            )
        if public_redacted and normalized in PUBLIC_IDENTITY_KEYS:
            errors.append(
                f"{label}: public_redacted record contains identity-like key "
                f"at {location}"
            )

    def visit_string(text: str, location: str) -> None:
        if BEARER_PATTERN.search(text):
            errors.append(
                f"{label}: record contains a bearer token at {location}"
            )
        elif JWT_PATTERN.search(text):
            errors.append(
                f"{label}: record contains a JWT at {location}"
            )
        elif PRIVATE_KEY_PATTERN.search(text):
            errors.append(
                f"{label}: record contains private-key material at {location}"
            )
        elif any(pattern.search(text) for pattern in API_KEY_PATTERNS):
            errors.append(
                f"{label}: record contains an API-key pattern at {location}"
            )
        if public_redacted and EMAIL_PATTERN.search(text):
            errors.append(
                f"{label}: public_redacted record contains an email at {location}"
            )

    _walk_json(
        value,
        path="$",
        key_visitor=visit_key,
        string_visitor=visit_string,
    )


def _validate_record_specific_safety(
    value: Mapping[str, Any],
    *,
    kind: str,
    label: str,
    errors: list[str],
) -> None:
    if kind == "devpost":
        required_flags = {
            "automaticSubmission": False,
            "legalAttestationsOwnerOnly": True,
            "finalSubmitted": False,
        }
        for field, expected in required_flags.items():
            if value.get(field) is not expected:
                errors.append(f"{label}: {field} must be {expected!r}")

    if kind == "payments":
        network = value.get("network")
        counted_as_revenue = value.get("countedAsRevenue")
        paying_customer = value.get("payingCustomer")
        moves_funds = value.get("movesFunds")
        if "movesFunds" in value and not isinstance(moves_funds, bool):
            errors.append(f"{label}: movesFunds must be a boolean")
        if network is not None and network not in {"ARC-TESTNET", "BASE-SEPOLIA"}:
            errors.append(f"{label}: payment network must be testnet-only")
        if (
            "countedAsRevenue" in value
            and counted_as_revenue is not False
        ):
            errors.append(f"{label}: countedAsRevenue must be false")
        if "payingCustomer" in value and paying_customer is not False:
            errors.append(
                f"{label}: payingCustomer must be false"
            )
        if moves_funds is True:
            if network not in {"ARC-TESTNET", "BASE-SEPOLIA"}:
                errors.append(
                    f"{label}: movesFunds=true requires a supported testnet network"
                )
            if counted_as_revenue is not False:
                errors.append(
                    f"{label}: movesFunds=true requires countedAsRevenue=false"
                )
            if paying_customer is not False:
                errors.append(
                    f"{label}: movesFunds=true requires payingCustomer=false"
                )

    if kind == "authorizations":
        if "mainnetEnabled" in value and value.get("mainnetEnabled") is not False:
            errors.append(f"{label}: mainnetEnabled must be false")
        payment_counts = [
            value[field]
            for field in ("maximumPaymentCount", "maxPaymentCount")
            if field in value
        ]
        if payment_counts:
            if any(
                isinstance(count, bool)
                or not isinstance(count, int)
                or count != 1
                for count in payment_counts
            ):
                errors.append(f"{label}: maximumPaymentCount must be integer 1")
            if any(count != payment_counts[0] for count in payment_counts[1:]):
                errors.append(f"{label}: payment-count fields must agree")

    if kind == "pilots":
        if (
            "countedAsRevenue" in value
            and value.get("countedAsRevenue") is not False
        ):
            errors.append(f"{label}: countedAsRevenue must be false")
        if "payingCustomer" in value and value.get("payingCustomer") is not False:
            errors.append(f"{label}: payingCustomer must be false")
        if "network" in value and value.get("network") != "ARC-TESTNET":
            errors.append(f"{label}: pilot network must be 'ARC-TESTNET'")
        if "token" in value and value.get("token") != "USDC":
            errors.append(f"{label}: pilot token must be 'USDC'")
        if "amountUsdc" in value:
            amount = value.get("amountUsdc")
            try:
                parsed_amount = (
                    None if isinstance(amount, bool) else Decimal(str(amount))
                )
            except (InvalidOperation, ValueError):
                parsed_amount = None
            if parsed_amount != Decimal("0.10"):
                errors.append(f"{label}: pilot amountUsdc must equal 0.10")


def _validate_record(
    value: Any,
    *,
    kind: str,
    label: str,
    errors: list[str],
) -> Mapping[str, Any] | None:
    if not isinstance(value, Mapping):
        errors.append(f"{label}: record must be a JSON object")
        return None

    if value.get("schemaVersion") != RECORD_SCHEMA:
        errors.append(f"{label}: schemaVersion must be {RECORD_SCHEMA!r}")

    record_id = _required_text(
        value.get("recordId"),
        label=f"{label}: recordId",
        errors=errors,
        slug=True,
    )
    if value.get("recordKind") != kind:
        errors.append(f"{label}: recordKind must match directory {kind!r}")
    if value.get("status") not in RECORD_STATUSES:
        errors.append(f"{label}: status is not an allowed OKF status")
    visibility = value.get("visibility")
    if visibility not in VISIBILITIES:
        errors.append(f"{label}: visibility must be private or public_redacted")

    created_at = _parse_utc_timestamp(
        value.get("createdAt"),
        label=f"{label}: createdAt",
        errors=errors,
    )
    updated_at = _parse_utc_timestamp(
        value.get("updatedAt"),
        label=f"{label}: updatedAt",
        errors=errors,
    )
    if created_at is not None and updated_at is not None and updated_at < created_at:
        errors.append(f"{label}: updatedAt must not precede createdAt")

    for field in ("title", "llmSummary", "claimBoundary"):
        _required_text(
            value.get(field),
            label=f"{label}: {field}",
            errors=errors,
        )
    if "nextAction" in value:
        _required_text(
            value.get("nextAction"),
            label=f"{label}: nextAction",
            errors=errors,
        )

    source_evidence = value.get("sourceEvidence")
    if not isinstance(source_evidence, list):
        errors.append(f"{label}: sourceEvidence must be a list")
    else:
        for index, source in enumerate(source_evidence):
            _required_text(
                source,
                label=f"{label}: sourceEvidence[{index}]",
                errors=errors,
            )

    links = value.get("links")
    if not isinstance(links, list):
        errors.append(f"{label}: links must be a list")
    else:
        seen_links: set[str] = set()
        for index, linked_id in enumerate(links):
            parsed_link = _required_text(
                linked_id,
                label=f"{label}: links[{index}]",
                errors=errors,
                slug=True,
            )
            if parsed_link is not None:
                if parsed_link in seen_links:
                    errors.append(f"{label}: duplicate link {parsed_link!r}")
                seen_links.add(parsed_link)
                if record_id is not None and parsed_link == record_id:
                    errors.append(f"{label}: record must not link to itself")

    _scan_record_security(
        value,
        label=label,
        public_redacted=visibility == "public_redacted",
        errors=errors,
    )
    _validate_record_specific_safety(
        value,
        kind=kind,
        label=label,
        errors=errors,
    )
    return value


def _is_within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
    except ValueError:
        return False
    return True


def _validate_real_workspace_directory(
    path: Path,
    *,
    workspace: Path,
    label: str,
    errors: list[str],
) -> bool:
    if path.is_symlink():
        errors.append(f"{label}: symlink directories are forbidden")
        return False
    if not path.is_dir():
        errors.append(f"{label}: missing directory")
        return False
    try:
        resolved = path.resolve(strict=True)
    except OSError as exc:
        errors.append(f"{label}: cannot resolve directory: {exc}")
        return False
    if not _is_within(resolved, workspace):
        errors.append(f"{label}: directory escapes the workspace")
        return False
    return True


def _scan_tree_for_symlinks_or_escapes(
    root: Path,
    *,
    workspace: Path,
    errors: list[str],
) -> None:
    try:
        candidates = sorted(root.rglob("*"), key=lambda item: item.as_posix())
    except OSError as exc:
        errors.append(f"{root.relative_to(workspace)}: cannot scan tree: {exc}")
        return
    for candidate in candidates:
        label = candidate.relative_to(workspace).as_posix()
        if candidate.is_symlink():
            errors.append(f"{label}: symlinks are forbidden in workspace trees")
            continue
        try:
            resolved = candidate.resolve(strict=True)
        except OSError as exc:
            errors.append(f"{label}: cannot resolve path: {exc}")
            continue
        if not _is_within(resolved, workspace):
            errors.append(f"{label}: path escapes the workspace")


def validate_workspace(root: str | os.PathLike[str]) -> ValidatedWorkspace:
    """Validate a workspace and return canonical records, or fail closed."""

    workspace = _normalize_root(root)
    errors: list[str] = []
    if not workspace.is_dir():
        raise WorkspaceValidationError((f"{workspace}: workspace does not exist",))
    try:
        root_children = sorted(workspace.iterdir(), key=lambda item: item.name)
    except OSError as exc:
        raise WorkspaceValidationError(
            (f"{workspace}: cannot inspect workspace: {exc}",)
        ) from exc
    for child in root_children:
        if child.is_symlink():
            errors.append(
                f"{child.name}: symlinked workspace-root children are forbidden"
            )

    manifest_path = workspace / ".okf-workspace.json"
    try:
        manifest_value = _load_json(manifest_path)
        manifest = _validate_manifest_value(
            manifest_value,
            label=".okf-workspace.json",
        )
    except (ValueError, WorkspaceValidationError) as exc:
        if isinstance(exc, WorkspaceValidationError):
            errors.extend(exc.errors)
        else:
            errors.append(str(exc))
        manifest = {}

    required_directories = (
        workspace / "records",
        workspace / "wiki",
        workspace / "runtime",
        workspace / "runtime" / "sqlite",
        workspace / "runtime" / "private-evidence",
        workspace / "publication-staging",
    )
    for directory in required_directories:
        _validate_real_workspace_directory(
            directory,
            workspace=workspace,
            label=directory.relative_to(workspace).as_posix(),
            errors=errors,
        )
    for tree_root in (workspace / "records", workspace / "wiki"):
        if tree_root.is_dir() and not tree_root.is_symlink():
            _scan_tree_for_symlinks_or_escapes(
                tree_root,
                workspace=workspace,
                errors=errors,
            )

    records: list[Record] = []
    records_by_id: dict[str, Record] = {}
    for kind in RECORD_KINDS:
        records_directory = workspace / "records" / kind
        wiki_directory = workspace / "wiki" / kind
        records_ok = _validate_real_workspace_directory(
            records_directory,
            workspace=workspace,
            label=records_directory.relative_to(workspace).as_posix(),
            errors=errors,
        )
        wiki_ok = _validate_real_workspace_directory(
            wiki_directory,
            workspace=workspace,
            label=wiki_directory.relative_to(workspace).as_posix(),
            errors=errors,
        )
        if not records_ok:
            continue

        paths = sorted(
            records_directory.rglob("*.json"),
            key=lambda item: item.relative_to(workspace).as_posix(),
        )
        for path in paths:
            if path.name.endswith(".template.json"):
                continue
            relative_path = path.relative_to(workspace)
            label = relative_path.as_posix()
            if path.is_symlink() or not path.is_file():
                errors.append(f"{label}: record must be a regular non-symlink file")
                continue
            try:
                raw_value = _load_json(path)
            except ValueError as exc:
                errors.append(str(exc))
                continue
            value = _validate_record(
                raw_value,
                kind=kind,
                label=label,
                errors=errors,
            )
            if value is None:
                continue
            record_id = value.get("recordId")
            if isinstance(record_id, str) and SLUG_PATTERN.fullmatch(record_id):
                record = Record(
                    path=path,
                    relative_path=relative_path,
                    data=value,
                )
                if record_id in records_by_id:
                    prior = records_by_id[record_id]
                    errors.append(
                        f"{label}: duplicate recordId {record_id!r}; first seen "
                        f"at {prior.relative_path.as_posix()}"
                    )
                else:
                    records_by_id[record_id] = record
                records.append(record)

    for record in records:
        links = record.data.get("links")
        if not isinstance(links, list):
            continue
        for linked_id in links:
            if isinstance(linked_id, str) and linked_id != record.record_id:
                if linked_id not in records_by_id:
                    errors.append(
                        f"{record.relative_path.as_posix()}: dangling link "
                        f"{linked_id!r}"
                    )

    if errors:
        raise WorkspaceValidationError(errors)

    ordered_records = tuple(
        sorted(
            records,
            key=lambda record: (
                RECORD_KINDS.index(record.record_kind),
                record.record_id,
                record.relative_path.as_posix(),
            ),
        )
    )
    return ValidatedWorkspace(
        root=workspace,
        manifest=manifest,
        records=ordered_records,
        records_by_id=dict(records_by_id),
    )


def _yaml_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, allow_nan=False)


def _record_page(record: Record) -> str:
    value = record.data
    digest = hashlib.sha256(_canonical_json_bytes(value)).hexdigest()
    lines = [
        "---",
        f"id: {record.record_id}",
        "pageType: memory",
        f"recordKind: {record.record_kind}",
        f"status: {value['status']}",
        f"visibility: {value['visibility']}",
        f"createdAt: {_yaml_json(value['createdAt'])}",
        f"updatedAt: {_yaml_json(value['updatedAt'])}",
        f"sources: {_yaml_json(value['sourceEvidence'])}",
        f"links: {_yaml_json(value['links'])}",
        f"claimBoundary: {_yaml_json(value['claimBoundary'])}",
        "---",
        GENERATED_MARKER,
        "",
        f"# {value['title']}",
        "",
        "## LLM summary",
        "",
        str(value["llmSummary"]),
        "",
        "## Claim boundary",
        "",
        str(value["claimBoundary"]),
    ]
    if "nextAction" in value:
        lines.extend(
            [
                "",
                "## Next action",
                "",
                str(value["nextAction"]),
            ]
        )
    lines.extend(
        [
            "",
            "## Canonical record",
            "",
            f"- JSON: `{record.relative_path.as_posix()}`",
            f"- SHA-256: `{digest}`",
            "",
        ]
    )
    return "\n".join(lines)


def _category_index(kind: str, records: Sequence[Record]) -> str:
    lines = [
        GENERATED_MARKER,
        f"# {kind.replace('_', ' ').title()}",
        "",
        f"{len(records)} canonical record(s).",
        "",
    ]
    for record in records:
        lines.append(
            f"- [{record.data['title']}]({record.record_id}.md) "
            f"— `{record.data['status']}` / `{record.data['visibility']}`"
        )
    lines.append("")
    return "\n".join(lines)


def _home_index(by_kind: Mapping[str, Sequence[Record]]) -> str:
    lines = [
        GENERATED_MARKER,
        "# Autonomerce private OKF workspace",
        "",
        "This wiki is generated from canonical private OKF JSON records.",
        "",
    ]
    for kind in RECORD_KINDS:
        lines.append(
            f"- [{kind.replace('_', ' ').title()}]({kind}/index.md) "
            f"— {len(by_kind[kind])} record(s)"
        )
    lines.append("")
    return "\n".join(lines)


def _is_generated_page(path: Path) -> bool:
    try:
        prefix = "\n".join(path.read_text(encoding="utf-8").splitlines()[:20])
    except (OSError, UnicodeError):
        return False
    return GENERATED_MARKER in prefix


def _ensure_generated_target(path: Path, *, wiki_root: Path) -> None:
    parent = path.parent
    if parent.is_symlink() or not parent.is_dir():
        raise WorkspaceValidationError(
            (f"{parent}: generated page parent must be a real directory",)
        )
    try:
        parent_resolved = parent.resolve(strict=True)
    except OSError as exc:
        raise WorkspaceValidationError(
            (f"{parent}: cannot resolve generated page parent: {exc}",)
        ) from exc
    if not _is_within(parent_resolved, wiki_root):
        raise WorkspaceValidationError(
            (f"{parent}: generated page parent escapes the wiki root",)
        )
    if path.is_symlink():
        raise WorkspaceValidationError(
            (f"{path}: generated page target must not be a symlink",)
        )
    if not path.exists():
        return
    if not path.is_file():
        raise WorkspaceValidationError(
            (f"{path}: generated page target is not a regular file",)
        )
    if not _is_generated_page(path):
        raise WorkspaceValidationError(
            (f"{path}: refusing to overwrite an unmarked user file",)
        )


def build_workspace(root: str | os.PathLike[str]) -> dict[str, Any]:
    """Validate records and emit deterministic, privacy-bounded Markdown."""

    validated = validate_workspace(root)
    by_kind: dict[str, list[Record]] = {kind: [] for kind in RECORD_KINDS}
    expected_pages: dict[Path, str] = {}
    for record in validated.records:
        by_kind[record.record_kind].append(record)
        expected_pages[
            validated.root
            / "wiki"
            / record.record_kind
            / f"{record.record_id}.md"
        ] = _record_page(record)

    for kind in RECORD_KINDS:
        expected_pages[validated.root / "wiki" / kind / "index.md"] = (
            _category_index(kind, by_kind[kind])
        )
    expected_pages[validated.root / "wiki" / "Home.md"] = _home_index(by_kind)

    wiki_root = validated.root / "wiki"
    for path in sorted(expected_pages, key=lambda item: item.as_posix()):
        _ensure_generated_target(path, wiki_root=wiki_root)
    for path, text in sorted(
        expected_pages.items(),
        key=lambda item: item[0].as_posix(),
    ):
        _atomic_write_private(path, text.encode("utf-8"))

    for path in sorted(wiki_root.rglob("*.md"), key=lambda item: item.as_posix()):
        if path in expected_pages or not path.is_file() or path.is_symlink():
            continue
        if _is_generated_page(path):
            path.unlink()

    return {
        "pageCount": len(expected_pages),
        "recordCount": len(validated.records),
        "root": str(validated.root),
        "status": "built",
    }


_MISSING = object()


def _nested_value(value: Mapping[str, Any], path: tuple[str, ...]) -> Any:
    current: Any = value
    for part in path:
        if not isinstance(current, Mapping) or part not in current:
            return _MISSING
        current = current[part]
    return current


def _coalesce(
    value: Mapping[str, Any],
    paths: Sequence[tuple[str, ...]],
    *,
    label: str,
    blockers: list[str],
    required: bool = True,
) -> Any:
    present = [
        (".".join(path), _nested_value(value, path))
        for path in paths
        if _nested_value(value, path) is not _MISSING
    ]
    if not present:
        if required:
            blockers.append(f"{label} is missing")
        return _MISSING
    first = present[0][1]
    if any(item != first for _, item in present[1:]):
        names = ", ".join(name for name, _ in present)
        blockers.append(f"{label} has conflicting values across {names}")
        return _MISSING
    return first


def _require_equal(
    actual: Any,
    expected: Any,
    *,
    label: str,
    blockers: list[str],
) -> None:
    if actual is _MISSING:
        return
    if isinstance(expected, bool):
        matches = actual is expected
    else:
        matches = actual == expected
    if not matches:
        blockers.append(f"{label} must be {expected!r}")


def _require_exact_usdc_amount(
    actual: Any,
    *,
    label: str,
    blockers: list[str],
) -> None:
    if actual is _MISSING:
        return
    if isinstance(actual, bool):
        blockers.append(f"{label} must equal exactly 0.10 USDC")
        return
    try:
        amount = Decimal(str(actual))
    except (InvalidOperation, ValueError):
        amount = None
    if amount != Decimal("0.10"):
        blockers.append(f"{label} must equal exactly 0.10 USDC")


def _require_path(
    value: Any,
    *,
    label: str,
    blockers: list[str],
    must_exist: bool,
) -> Path | None:
    if value is _MISSING:
        return None
    if not isinstance(value, str) or not value:
        blockers.append(f"{label} must be a non-empty path string")
        return None
    path = Path(value).expanduser()
    if not path.is_absolute():
        blockers.append(f"{label} must be an absolute path")
        return None
    current = Path(path.anchor)
    for part in path.parts[1:]:
        current /= part
        if current.is_symlink():
            blockers.append(
                f"{label} must not contain symlink path components: {current}"
            )
            return None
    if path.exists() and not path.is_file():
        blockers.append(f"{label} must not target a directory or non-regular file")
        return None
    if must_exist and not path.is_file():
        blockers.append(f"{label} must identify an existing regular file")
        return None
    try:
        resolved = path.resolve(strict=must_exist)
    except OSError as exc:
        blockers.append(f"{label} cannot be resolved: {exc}")
        return None
    return resolved


def _require_workspace_directory(
    path: Path,
    *,
    workspace: Path,
    label: str,
    blockers: list[str],
) -> Path | None:
    if not path.is_absolute():
        blockers.append(f"{label} must be an absolute path")
        return None
    current = Path(path.anchor)
    for part in path.parts[1:]:
        current /= part
        if current.is_symlink():
            blockers.append(
                f"{label} must not contain symlink path components: {current}"
            )
            return None
    if path.is_symlink() or not path.is_dir():
        blockers.append(f"{label} must be an existing real directory")
        return None
    try:
        resolved = path.resolve(strict=True)
    except OSError as exc:
        blockers.append(f"{label} cannot be resolved: {exc}")
        return None
    if not _is_within(resolved, workspace):
        blockers.append(f"{label} must remain under the validated workspace")
        return None
    return resolved


