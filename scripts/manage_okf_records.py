def _readiness_text(
    value: Any,
    *,
    label: str,
    blockers: list[str],
    maximum: int | None = None,
) -> str | None:
    if not isinstance(value, str) or not value.strip():
        blockers.append(f"{label} must be a non-empty string")
        return None
    text = value.strip()
    if any(ord(character) < 32 for character in text):
        blockers.append(f"{label} must not contain control characters")
        return None
    if maximum is not None and len(text) > maximum:
        blockers.append(f"{label} exceeds its size limit")
        return None
    return text


def _readiness_optional_text(
    value: Any,
    *,
    label: str,
    maximum: int,
    blockers: list[str],
) -> str | None:
    if value is None:
        return ""
    if not isinstance(value, str):
        blockers.append(f"{label} must be a string")
        return None
    text = value.strip()
    if len(text) > maximum:
        blockers.append(f"{label} exceeds its size limit")
        return None
    return text


def _load_customer_record_facts(
    path: Path,
    *,
    blockers: list[str],
) -> CustomerRecordFacts | None:
    try:
        raw = path.read_bytes()
    except OSError as exc:
        blockers.append(f"customer record could not be read: {exc}")
        return None
    if not raw or len(raw) > MAX_CUSTOMER_RECORD_BYTES:
        blockers.append("customer record is empty or exceeds its size limit")
        return None
    try:
        decoded = raw.decode("utf-8")
        value = json.loads(
            decoded,
            object_pairs_hook=_json_object,
            parse_constant=_reject_json_constant,
        )
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        blockers.append(f"customer record must be strict UTF-8 JSON: {exc}")
        return None
    if not isinstance(value, Mapping):
        blockers.append("customer record must be a JSON object")
        return None

    customer_record_id = _readiness_text(
        value.get("customerRecordId"),
        label="customerRecord.customerRecordId",
        blockers=blockers,
        maximum=160,
    )
    relationship = value.get("relationship")
    if not isinstance(relationship, Mapping):
        blockers.append("customerRecord.relationship must be a JSON object")
        relationship = {}
    relationship_record_id = _readiness_text(
        relationship.get("relationshipRecordId"),
        label="customerRecord.relationship.relationshipRecordId",
        blockers=blockers,
        maximum=160,
    )
    classification = _readiness_text(
        relationship.get("classification"),
        label="customerRecord.relationship.classification",
        blockers=blockers,
        maximum=80,
    )
    if classification is not None and classification != "external_design_partner":
        blockers.append(
            "customerRecord.relationship.classification must be "
            "'external_design_partner'"
        )

    consent = value.get("consent")
    if not isinstance(consent, Mapping):
        blockers.append("customerRecord.consent must be a JSON object")
        consent = {}
    consent_record_id = _readiness_text(
        consent.get("consentRecordId"),
        label="customerRecord.consent.consentRecordId",
        blockers=blockers,
        maximum=160,
    )
    consent_status = _readiness_text(
        consent.get("status"),
        label="customerRecord.consent.status",
        blockers=blockers,
        maximum=32,
    )
    if consent_status is not None and consent_status.lower() != "granted":
        blockers.append("customerRecord.consent.status must be 'granted'")
    for field in (
        "designPartnerPilot",
        "testnetMicrodeal",
        "publishRedactedEvidence",
    ):
        if consent.get(field) is not True:
            blockers.append(f"customerRecord.consent.{field} must be true")

    _require_https_url(
        value.get("buyerAgentUrl", _MISSING),
        label="customerRecord.buyerAgentUrl",
        blockers=blockers,
    )

    claims = value.get("claims")
    if not isinstance(claims, list) or not 1 <= len(claims) <= 5:
        blockers.append("customerRecord.claims must contain 1 to 5 claims")
    else:
        for claim_index, claim_value in enumerate(claims):
            claim_label = f"customerRecord.claims[{claim_index}]"
            if not isinstance(claim_value, Mapping):
                blockers.append(f"{claim_label} must be a JSON object")
                continue
            if set(claim_value) - {"claim", "sources"}:
                blockers.append(f"{claim_label} contains unsupported fields")
            _readiness_text(
                claim_value.get("claim"),
                label=f"{claim_label}.claim",
                blockers=blockers,
                maximum=8_000,
            )
            sources = claim_value.get("sources")
            if not isinstance(sources, list) or not sources:
                blockers.append(f"{claim_label}.sources must be non-empty")
                continue
            if len(sources) > 25:
                blockers.append(f"{claim_label}.sources exceeds 25 entries")
                continue
            seen_source_ids: set[str] = set()
            for source_index, source_value in enumerate(sources):
                source_label = f"{claim_label}.sources[{source_index}]"
                if not isinstance(source_value, Mapping):
                    blockers.append(f"{source_label} must be a JSON object")
                    continue
                if set(source_value) - {
                    "sourceId",
                    "url",
                    "title",
                    "excerpt",
                    "stance",
                }:
                    blockers.append(
                        f"{source_label} contains unsupported fields"
                    )
                _require_source_https_url(
                    source_value.get("url"),
                    label=f"{source_label}.url",
                    blockers=blockers,
                )
                supplied_id = source_value.get("sourceId")
                if supplied_id is not None:
                    source_id = _readiness_text(
                        supplied_id,
                        label=f"{source_label}.sourceId",
                        blockers=blockers,
                        maximum=128,
                    )
                    if source_id is not None:
                        if not all(
                            character.isalnum() or character in "._:-"
                            for character in source_id
                        ):
                            blockers.append(
                                f"{source_label}.sourceId contains invalid characters"
                            )
                        if source_id in seen_source_ids:
                            blockers.append(
                                f"{claim_label}.sources contain duplicate sourceId"
                            )
                        seen_source_ids.add(source_id)
                _readiness_optional_text(
                    source_value.get("title"),
                    label=f"{source_label}.title",
                    maximum=500,
                    blockers=blockers,
                )
                _readiness_optional_text(
                    source_value.get("excerpt"),
                    label=f"{source_label}.excerpt",
                    maximum=8_000,
                    blockers=blockers,
                )
                stance = str(source_value.get("stance", "context")).strip().lower()
                if stance not in {"support", "refute", "context"}:
                    blockers.append(
                        f"{source_label}.stance must be support, refute, or context"
                    )

    if (
        customer_record_id is None
        or relationship_record_id is None
        or consent_record_id is None
    ):
        return None
    return CustomerRecordFacts(
        customer_record_id=customer_record_id,
        relationship_record_id=relationship_record_id,
        consent_record_id=consent_record_id,
    )


def _readiness_packet_base(pilot_id: str) -> dict[str, Any]:
    return {
        "dryRunBlockers": [],
        "dryRunCommand": [],
        "executionBlockers": [
            "Fresh owner approval is required immediately before any execution.",
            (
                "Exact execution confirmation "
                f"{EXECUTION_CONFIRMATION!r} is required; this readiness command "
                "does not emit or apply it."
            ),
        ],
        "linkedRecords": {},
        "pilotId": pilot_id,
        "readyForDryRun": False,
        "readyForExecution": False,
        "schemaVersion": READINESS_SCHEMA,
    }


def pilot_readiness(
    root: str | os.PathLike[str],
    pilot_id: str,
) -> dict[str, Any]:
    """Build a fail-closed dry-run packet without executing any command."""

    packet = _readiness_packet_base(pilot_id)
    blockers: list[str] = packet["dryRunBlockers"]
    if not isinstance(pilot_id, str) or not SLUG_PATTERN.fullmatch(pilot_id):
        blockers.append("pilot ID must be a lowercase hyphenated slug")
        return packet

    try:
        validated = validate_workspace(root)
    except WorkspaceValidationError as exc:
        blockers.extend(f"workspace validation: {error}" for error in exc.errors)
        return packet

    pilot = validated.records_by_id.get(pilot_id)
    if pilot is None or pilot.record_kind != "pilots":
        blockers.append(f"pilot record {pilot_id!r} was not found")
        return packet

    packet["linkedRecords"]["pilot"] = pilot.record_id
    links = pilot.data["links"]
    linked = [
        validated.records_by_id[linked_id]
        for linked_id in links
        if linked_id in validated.records_by_id
    ]
    selected: dict[str, Record] = {}
    for kind, singular in (
        ("partners", "partner"),
        ("consents", "consent"),
        ("authorizations", "authorization"),
    ):
        matches = [record for record in linked if record.record_kind == kind]
        if len(matches) != 1:
            blockers.append(
                f"pilot must link exactly one {singular} record; found {len(matches)}"
            )
        else:
            selected[singular] = matches[0]
            packet["linkedRecords"][singular] = matches[0].record_id
    if len(selected) != 3:
        return packet

    partner = selected["partner"].data
    consent = selected["consent"].data
    authorization = selected["authorization"].data
    current_utc = datetime.now(timezone.utc)

    if pilot.data.get("status") != "ready":
        blockers.append("pilot status must be 'ready' for dry-run readiness")
    if partner.get("status") not in {"ready", "verified"}:
        blockers.append("partner status must be ready or verified")
    if consent.get("status") not in {"ready", "verified", "authorized"}:
        blockers.append(
            "consent record status must be ready, verified, or authorized"
        )

    linked_id_fields = (
        ("partnerRecordId", "partner"),
        ("consentRecordId", "consent"),
        ("authorizationRecordId", "authorization"),
    )
    for field, singular in linked_id_fields:
        if field in pilot.data and pilot.data[field] != selected[singular].record_id:
            blockers.append(
                f"pilot {field} must match linked {singular} "
                f"{selected[singular].record_id!r}"
            )
    if (
        "partnerRecordId" in consent
        and consent["partnerRecordId"] != selected["partner"].record_id
    ):
        blockers.append("consent partnerRecordId must match the linked partner")

    identified_pilot = authorization.get("pilotRecordId", _MISSING)
    authorized_pilot_ids = authorization.get("authorizedPilotIds", _MISSING)
    if identified_pilot is _MISSING and authorized_pilot_ids is _MISSING:
        blockers.append(
            "authorization must identify the pilot via pilotRecordId or "
            "authorizedPilotIds"
        )
    if identified_pilot is not _MISSING and identified_pilot != pilot.record_id:
        blockers.append("authorization pilotRecordId must match the selected pilot")
    if authorized_pilot_ids is not _MISSING:
        if (
            not isinstance(authorized_pilot_ids, list)
            or len(authorized_pilot_ids) != 1
            or authorized_pilot_ids[0] != pilot.record_id
        ):
            blockers.append(
                "authorization authorizedPilotIds must contain only the selected "
                "pilot"
            )
    active_authorization_pilots = [
        record
        for record in validated.records
        if (
            record.record_kind == "pilots"
            and selected["authorization"].record_id in record.data.get("links", [])
            and record.data.get("status") not in {"rejected", "superseded"}
        )
    ]
    if len(active_authorization_pilots) != 1:
        blockers.append(
            "authorization must be linked by exactly one active pilot; found "
            f"{len(active_authorization_pilots)}"
        )
    elif active_authorization_pilots[0].record_id != pilot.record_id:
        blockers.append("authorization is linked to a different active pilot")

    microdeal_id = pilot.data.get("microdealId", pilot_id)
    if not isinstance(microdeal_id, str) or not SLUG_PATTERN.fullmatch(microdeal_id):
        blockers.append("pilot microdealId must be a lowercase hyphenated slug")
    authorization_microdeal_id = authorization.get("microdealId")
    if authorization_microdeal_id != microdeal_id:
        blockers.append(
            "authorization microdealId must match pilot microdealId exactly"
        )

    pilot_network = pilot.data.get("network", _MISSING)
    if pilot_network is not _MISSING:
        _require_equal(
            pilot_network,
            "ARC-TESTNET",
            label="pilot network",
            blockers=blockers,
        )
    pilot_token = pilot.data.get("token", _MISSING)
    if pilot_token is not _MISSING:
        _require_equal(
            pilot_token,
            "USDC",
            label="pilot token",
            blockers=blockers,
        )
    _require_exact_usdc_amount(
        pilot.data.get("amountUsdc", _MISSING),
        label="pilot amount",
        blockers=blockers,
    )
    pilot_funding_source = pilot.data.get("fundingSource", _MISSING)
    if pilot_funding_source is not _MISSING:
        _require_equal(
            pilot_funding_source,
            "founder_sponsored_testnet",
            label="pilot fundingSource",
            blockers=blockers,
        )
    for field in ("countedAsRevenue", "payingCustomer"):
        if field in pilot.data:
            _require_equal(
                pilot.data[field],
                False,
                label=f"pilot {field}",
                blockers=blockers,
            )

    classification = _coalesce(
        partner,
        (
            ("classification",),
            ("relationshipClassification",),
            ("relationship", "classification"),
        ),
        label="partner classification",
        blockers=blockers,
    )
    _require_equal(
        classification,
        "external_design_partner",
        label="partner classification",
        blockers=blockers,
    )
    arms_length = _coalesce(
        partner,
        (
            ("armsLength",),
            ("relationship", "armsLength"),
        ),
        label="partner armsLength",
        blockers=blockers,
    )
    _require_equal(
        arms_length,
        True,
        label="partner armsLength",
        blockers=blockers,
    )
    recruitment_status = _coalesce(
        partner,
        (
            ("recruitmentStatus",),
            ("recruitment", "status"),
        ),
        label="partner recruitment status",
        blockers=blockers,
    )
    _require_equal(
        recruitment_status,
        "accepted",
        label="partner recruitment status",
        blockers=blockers,
    )

    consent_status = _coalesce(
        consent,
        (
            ("consentStatus",),
            ("grantStatus",),
            ("consent", "status"),
        ),
        label="consent grant status",
        blockers=blockers,
    )
    _require_equal(
        consent_status,
        "granted",
        label="consent grant status",
        blockers=blockers,
    )
    for field in (
        "designPartnerPilot",
        "testnetMicrodeal",
        "publishRedactedEvidence",
    ):
        permission = _coalesce(
            consent,
            (
                (field,),
                ("consent", field),
                ("permissions", field),
            ),
            label=f"consent {field}",
            blockers=blockers,
        )
        _require_equal(
            permission,
            True,
            label=f"consent {field}",
            blockers=blockers,
        )

    _require_equal(
        authorization.get("status", _MISSING),
        "authorized",
        label="authorization status",
        blockers=blockers,
    )
    authorized_at = _readiness_utc_timestamp(
        authorization.get("authorizedAt"),
        label="authorization authorizedAt",
        blockers=blockers,
    )
    expires_at = _readiness_utc_timestamp(
        authorization.get("expiresAt"),
        label="authorization expiresAt",
        blockers=blockers,
    )
    if authorized_at is not None and expires_at is not None:
        if authorized_at > current_utc:
            blockers.append("authorization authorizedAt must not be in the future")
        if expires_at <= authorized_at:
            blockers.append("authorization expiresAt must be after authorizedAt")
        if expires_at <= current_utc:
            blockers.append("authorization expiresAt must be in the future")

    network = _coalesce(
        authorization,
        (
            ("network",),
            ("chain",),
            ("payment", "network"),
            ("payment", "chain"),
        ),
        label="authorization network",
        blockers=blockers,
    )
    _require_equal(
        network,
        "ARC-TESTNET",
        label="authorization network",
        blockers=blockers,
    )
    token = _coalesce(
        authorization,
        (
            ("token",),
            ("payment", "token"),
        ),
        label="authorization token",
        blockers=blockers,
    )
    _require_equal(
        token,
        "USDC",
        label="authorization token",
        blockers=blockers,
    )
    amount = _coalesce(
        authorization,
        (
            ("amountUsdc",),
            ("amount",),
            ("payment", "amountUsdc"),
            ("payment", "amount"),
        ),
        label="authorization amount",
        blockers=blockers,
    )
    _require_exact_usdc_amount(
        amount,
        label="authorization amount",
        blockers=blockers,
    )

    maximum_payment_count = _coalesce(
        authorization,
        (
            ("maxPaymentCount",),
            ("maximumPaymentCount",),
            ("payment", "maxPaymentCount"),
            ("payment", "maximumPaymentCount"),
        ),
        label="authorization maxPaymentCount",
        blockers=blockers,
    )
    if (
        maximum_payment_count is not _MISSING
        and (
            isinstance(maximum_payment_count, bool)
            or not isinstance(maximum_payment_count, int)
            or maximum_payment_count != 1
        )
    ):
        blockers.append("authorization maxPaymentCount must be integer 1")

    mainnet_enabled = _coalesce(
        authorization,
        (
            ("mainnetEnabled",),
            ("payment", "mainnetEnabled"),
            ("policy", "mainnetEnabled"),
        ),
        label="authorization mainnetEnabled",
        blockers=blockers,
    )
    _require_equal(
        mainnet_enabled,
        False,
        label="authorization mainnetEnabled",
        blockers=blockers,
    )
    funding_source = _coalesce(
        authorization,
        (
            ("fundingSource",),
            ("payment", "fundingSource"),
        ),
        label="authorization fundingSource",
        blockers=blockers,
    )
    _require_equal(
        funding_source,
        "founder_sponsored_testnet",
        label="authorization fundingSource",
        blockers=blockers,
    )

    payer = _coalesce(
        authorization,
        (
            ("payerWallet",),
            ("payer",),
            ("payment", "payerWallet"),
            ("payment", "payer"),
        ),
        label="authorization payer",
        blockers=blockers,
    )
    payee = _coalesce(
        authorization,
        (
            ("payeeWallet",),
            ("payee",),
            ("payment", "payeeWallet"),
            ("payment", "payee"),
        ),
        label="authorization payee",
        blockers=blockers,
    )
    for value, label in ((payer, "payer"), (payee, "payee")):
        if value is not _MISSING and (
            not isinstance(value, str) or not WALLET_PATTERN.fullmatch(value)
        ):
            blockers.append(f"authorization {label} must be a 20-byte hex wallet")
    if payer is not _MISSING and payee is not _MISSING and payer.lower() == payee.lower():
        blockers.append("authorization payer and payee must be distinct")

    circle_path_value = _coalesce(
        authorization,
        (
            ("circleCliPath",),
            ("circleCliBinary",),
            ("circleCli", "path"),
            ("circleCli", "binary"),
        ),
        label="authorization Circle CLI path",
        blockers=blockers,
    )
    circle_hash = _coalesce(
        authorization,
        (
            ("circleCliSha256",),
            ("circleCli", "sha256"),
        ),
        label="authorization Circle CLI SHA-256",
        blockers=blockers,
    )
    circle_path = _require_path(
        circle_path_value,
        label="authorization Circle CLI path",
        blockers=blockers,
        must_exist=True,
    )
    if circle_hash is not _MISSING and (
        not isinstance(circle_hash, str)
        or not SHA256_PATTERN.fullmatch(circle_hash)
    ):
        blockers.append(
            "authorization Circle CLI SHA-256 must be 64 lowercase hex characters"
        )
    elif circle_path is not None:
        try:
            actual_hash = hashlib.sha256(circle_path.read_bytes()).hexdigest()
        except OSError as exc:
            blockers.append(f"authorization Circle CLI cannot be read: {exc}")
            actual_hash = None
        if actual_hash != circle_hash:
            blockers.append(
                "authorization Circle CLI SHA-256 does not match the pinned file"
            )

    customer_record_value = _coalesce(
        pilot.data,
        (
            ("customerRecordPath",),
            ("runtime", "customerRecordPath"),
        ),
        label="pilot customerRecordPath",
        blockers=blockers,
        required=False,
    )
    if customer_record_value is _MISSING:
        customer_record_value = _coalesce(
            authorization,
            (
                ("customerRecordPath",),
                ("paths", "customerRecord"),
            ),
            label="customer record path",
            blockers=blockers,
        )
    customer_record_path = _require_path(
        customer_record_value,
        label="customer record path",
        blockers=blockers,
        must_exist=True,
    )
    customer_facts = (
        _load_customer_record_facts(customer_record_path, blockers=blockers)
        if customer_record_path is not None
        else None
    )
    if customer_facts is not None:
        expected_ids = {
            "customerRecordId": customer_facts.customer_record_id,
            "relationshipRecordId": customer_facts.relationship_record_id,
            "consentRecordId": customer_facts.consent_record_id,
        }
        for okf_label, okf_record in (
            ("partner", partner),
            ("consent", consent),
        ):
            for field, expected in expected_ids.items():
                if field in okf_record and okf_record[field] != expected:
                    blockers.append(
                        f"{okf_label} {field} must match customer record "
                        f"{expected!r}"
                    )

    sqlite_path = _require_path(
        _coalesce(
            authorization,
            (
                ("sqlitePath",),
                ("paths", "sqlite"),
            ),
            label="authorization sqlite path",
            blockers=blockers,
        ),
        label="authorization sqlite path",
        blockers=blockers,
        must_exist=False,
    )
    private_evidence_path = _require_path(
        _coalesce(
            authorization,
            (
                ("privateEvidencePath",),
                ("paths", "privateEvidence"),
            ),
            label="authorization private evidence path",
            blockers=blockers,
        ),
        label="authorization private evidence path",
        blockers=blockers,
        must_exist=False,
    )
    public_evidence_path = _require_path(
        _coalesce(
            authorization,
            (
                ("publicEvidencePath",),
                ("paths", "publicEvidence"),
            ),
            label="authorization public evidence path",
            blockers=blockers,
        ),
        label="authorization public evidence path",
        blockers=blockers,
        must_exist=False,
    )
    for forbidden_root_path in (
        ("privateEvidenceRoot",),
        ("paths", "privateEvidenceRoot"),
        ("publicationStagingRoot",),
        ("paths", "publicationStagingRoot"),
    ):
        if _nested_value(authorization, forbidden_root_path) is not _MISSING:
            blockers.append(
                "authorization must not configure private-evidence or publication "
                "roots"
            )
    sqlite_root = _require_workspace_directory(
        validated.root / "runtime" / "sqlite",
        workspace=validated.root,
        label="workspace SQLite root",
        blockers=blockers,
    )
    private_evidence_root = _require_workspace_directory(
        validated.root / "runtime" / "private-evidence",
        workspace=validated.root,
        label="workspace private evidence root",
        blockers=blockers,
    )
    publication_staging_root = _require_workspace_directory(
        validated.root / "publication-staging",
        workspace=validated.root,
        label="workspace publication staging root",
        blockers=blockers,
    )
    _require_workspace_output_path(
        sqlite_path,
        workspace=validated.root,
        allowed_root=sqlite_root,
        label="SQLite path",
        blockers=blockers,
    )
    _require_workspace_output_path(
        private_evidence_path,
        workspace=validated.root,
        allowed_root=private_evidence_root,
        label="private evidence path",
        blockers=blockers,
    )
    _require_workspace_output_path(
        public_evidence_path,
        workspace=validated.root,
        allowed_root=publication_staging_root,
        label="public evidence path",
        blockers=blockers,
    )
    private_paths = [
        path
        for path in (
            customer_record_path,
            sqlite_path,
            private_evidence_path,
            public_evidence_path,
        )
        if path is not None
    ]
    if len(private_paths) == 4 and len(set(private_paths)) != 4:
        blockers.append(
            "customer record, SQLite, private evidence, and public evidence "
            "paths must be distinct"
        )

    authorization_seller_url = _coalesce(
        authorization,
        (
            ("sellerAgentUrl",),
            ("sellerUrl",),
            ("seller", "url"),
        ),
        label="authorization seller URL",
        blockers=blockers,
        required=False,
    )
    pilot_seller_url = _coalesce(
        pilot.data,
        (
            ("sellerAgentUrl",),
            ("sellerUrl",),
            ("seller", "url"),
        ),
        label="pilot seller URL",
        blockers=blockers,
        required=False,
    )
    canonical_authorization_seller = (
        _require_https_url(
            authorization_seller_url,
            label="authorization seller URL",
            blockers=blockers,
        )
        if authorization_seller_url is not _MISSING
        else None
    )
    canonical_pilot_seller = (
        _require_https_url(
            pilot_seller_url,
            label="pilot seller URL",
            blockers=blockers,
        )
        if pilot_seller_url is not _MISSING
        else None
    )
    if (
        canonical_authorization_seller is not None
        and canonical_pilot_seller is not None
        and canonical_authorization_seller != canonical_pilot_seller
    ):
        blockers.append("pilot and authorization seller URLs must match")
        seller_url = None
    elif canonical_authorization_seller is not None:
        seller_url = canonical_authorization_seller
    elif canonical_pilot_seller is not None:
        seller_url = canonical_pilot_seller
    else:
        seller_url = None
        if (
            authorization_seller_url is _MISSING
            and pilot_seller_url is _MISSING
        ):
            blockers.append("seller URL is missing")

    interpreter_value = _coalesce(
        authorization,
        (
            ("circleCliInterpreter",),
            ("circleCli", "interpreter"),
        ),
        label="authorization Circle CLI interpreter",
        blockers=blockers,
        required=False,
    )
    interpreter_hash = _coalesce(
        authorization,
        (
            ("circleCliInterpreterSha256",),
            ("circleCli", "interpreterSha256"),
        ),
        label="authorization Circle CLI interpreter SHA-256",
        blockers=blockers,
        required=False,
    )
    interpreter_path: Path | None = None
    if interpreter_value == "" and interpreter_hash == "":
        interpreter_value = _MISSING
        interpreter_hash = _MISSING
    if (interpreter_value is _MISSING) != (interpreter_hash is _MISSING):
        blockers.append(
            "Circle CLI interpreter path and SHA-256 must be provided together"
        )
    elif interpreter_value is not _MISSING:
        interpreter_path = _require_path(
            interpreter_value,
            label="authorization Circle CLI interpreter",
            blockers=blockers,
            must_exist=True,
        )
        if (
            not isinstance(interpreter_hash, str)
            or not SHA256_PATTERN.fullmatch(interpreter_hash)
        ):
            blockers.append(
                "Circle CLI interpreter SHA-256 must be 64 lowercase hex characters"
            )
        elif interpreter_path is not None:
            try:
                actual_interpreter_hash = hashlib.sha256(
                    interpreter_path.read_bytes()
                ).hexdigest()
            except OSError as exc:
                blockers.append(f"Circle CLI interpreter cannot be read: {exc}")
                actual_interpreter_hash = None
            if actual_interpreter_hash != interpreter_hash:
                blockers.append(
                    "Circle CLI interpreter SHA-256 does not match the pinned file"
                )
    if interpreter_path is None:
        _require_executable_bit(
            circle_path,
            label="Circle CLI",
            blockers=blockers,
        )
    else:
        _require_executable_bit(
            interpreter_path,
            label="Circle CLI interpreter",
            blockers=blockers,
        )

    if not MICRODEAL_RUNNER.is_file():
        blockers.append(f"microdeal runner is missing at {MICRODEAL_RUNNER}")

    if blockers:
        return packet

    command = [
        sys.executable,
        str(MICRODEAL_RUNNER),
        "--dry-run",
        "--microdeal-id",
        str(microdeal_id),
        "--customer-record",
        str(customer_record_path),
        "--payer-wallet",
        str(payer),
        "--payee-wallet",
        str(payee),
        "--seller-agent-url",
        str(seller_url),
        "--circle-cli-binary",
        str(circle_path),
        "--circle-cli-sha256",
        str(circle_hash),
        "--sqlite-path",
        str(sqlite_path),
        "--private-evidence-path",
        str(private_evidence_path),
        "--public-evidence-path",
        str(public_evidence_path),
    ]
    if interpreter_path is not None:
        command.extend(
            [
                "--circle-cli-interpreter",
                str(interpreter_path),
                "--circle-cli-interpreter-sha256",
                str(interpreter_hash),
            ]
        )
    packet["dryRunCommand"] = command
    packet["readyForDryRun"] = True
    return packet


def _write_packet_output(path: Path, packet: Mapping[str, Any]) -> None:
    _atomic_write_private(path.expanduser().resolve(), _pretty_json(packet).encode())


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Manage a private, local Autonomerce OKF record workspace."
    )
    subparsers = parser.add_subparsers(dest="command", required=True)
    for command in ("init", "validate", "build"):
        subparser = subparsers.add_parser(command)
        subparser.add_argument("--root", required=True, type=Path)

    readiness = subparsers.add_parser("pilot-readiness")
    readiness.add_argument("--root", required=True, type=Path)
    readiness.add_argument("--pilot-id", required=True)
    readiness.add_argument("--output", type=Path)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "init":
            result = init_workspace(args.root)
        elif args.command == "validate":
            validated = validate_workspace(args.root)
            result = {
                "recordCount": len(validated.records),
                "root": str(validated.root),
                "status": "valid",
            }
        elif args.command == "build":
            result = build_workspace(args.root)
        else:
            result = pilot_readiness(args.root, args.pilot_id)
            if args.output is not None:
                _write_packet_output(args.output, result)
            print(_pretty_json(result), end="")
            return 0 if result["readyForDryRun"] else 1
    except WorkspaceValidationError as exc:
        print(
            _pretty_json({"errors": list(exc.errors), "status": "invalid"}),
            end="",
            file=sys.stderr,
        )
        return 1
    except (OSError, ValueError) as exc:
        print(
            _pretty_json({"errors": [str(exc)], "status": "invalid"}),
            end="",
            file=sys.stderr,
        )
        return 1

    print(_pretty_json(result), end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
